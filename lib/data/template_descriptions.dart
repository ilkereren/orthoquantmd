**Glenoid Bone Loss Measurement**
This template quantifies anterior glenoid bone loss using the best-fit circle method, a widely accepted technique in shoulder instability assessment.

**Measurement Principle**
- A circle representing the native glenoid surface is reconstructed by fitting a best-fit circle to the intact posterior and inferior glenoid rim, which is assumed to remain anatomically preserved in anterior instability.
- The bone defect is calculated as the loss of glenoid diameter relative to the expected native diameter derived from the fitted circle.
- Bone loss is expressed as a percentage of the glenoid diameter.
- The missing anterior portion is quantified by comparing the expected diameter to the remaining anterior–posterior width.
- This method allows standardized comparison across patients and imaging modalities.

**Clinical Relevance**
- Glenoid bone loss is a key determinant in the management of anterior shoulder instability.
- Increasing bone loss is associated with higher failure rates after isolated soft-tissue stabilization.
- Quantification of bone loss supports surgical decision-making, including the consideration of bone augmentation procedures.

